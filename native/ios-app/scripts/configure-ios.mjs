/**
 * Run after `npx cap add ios` / `npx cap sync ios` on macOS.
 * Makes the native Documents directory visible in the Files app and adds
 * Apple's filesystem-access privacy manifest. Never modifies photo data.
 */
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("../", import.meta.url)));
const app = join(root, "ios", "App", "App");
const plist = join(app, "Info.plist");
const projectPath = join(root, "ios", "App", "App.xcodeproj");

if (!existsSync(plist)) {
  throw new Error("No iOS project found. Run: npx cap add ios");
}

function setPlistBoolean(key) {
  const utility = "/usr/libexec/PlistBuddy";
  try {
    execFileSync(utility, ["-c", "Set :" + key + " true", plist], { stdio: "pipe" });
  } catch {
    execFileSync(utility, ["-c", "Add :" + key + " bool true", plist], { stdio: "inherit" });
  }
}
setPlistBoolean("UIFileSharingEnabled");
setPlistBoolean("LSSupportsOpeningDocumentsInPlace");

const privacy = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>NSPrivacyAccessedAPITypes</key>
  <array>
    <dict>
      <key>NSPrivacyAccessedAPIType</key>
      <string>NSPrivacyAccessedAPICategoryFileTimestamp</string>
      <key>NSPrivacyAccessedAPITypeReasons</key>
      <array>
        <string>C617.1</string>
      </array>
    </dict>
  </array>
</dict>
</plist>
`;
const privacyFile = join(app, "PrivacyInfo.xcprivacy");
writeFileSync(privacyFile, privacy);

// Xcode's project is generated by Capacitor and is not checked in. Use the
// xcodeproj Ruby library installed by CocoaPods to add the manifest to the
// App target's Copy Bundle Resources phase.
const ruby = `
require 'xcodeproj'
p = Xcodeproj::Project.open(ARGV[0])
target = p.targets.find { |t| t.name == 'App' }
raise 'App target not found' unless target
group = p.main_group.find_subpath('App', true)
file = group.find_file_by_path('PrivacyInfo.xcprivacy') || group.new_file('PrivacyInfo.xcprivacy')
unless target.resources_build_phase.files_references.any? { |f| f.path == file.path }
  target.resources_build_phase.add_file_reference(file)
end
p.save
`;
try {
  execFileSync("ruby", ["-e", ruby, projectPath], { stdio: "inherit" });
} catch (error) {
  throw new Error(
    "Could not add PrivacyInfo.xcprivacy to the Xcode app target. " +
    "Install CocoaPods/xcodeproj or add the file to App > Build Phases > Copy Bundle Resources. " +
    error.message
  );
}
console.log("Configured native Files visibility and privacy declaration.");
